// Language Engine Core
class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('megakarya_lang') || 'id';
  }

  init(pageScope) {
    this.pageScope = pageScope;
    this.applyLanguage(this.currentLang);
    this.renderLanguageSwitcher();
  }

  setLanguage(lang) {
    if (lang !== 'id' && lang !== 'en') return;
    this.currentLang = lang;
    localStorage.setItem('megakarya_lang', lang);
    this.applyLanguage(lang);
    this.updateSwitcherUI();
  }

  applyLanguage(lang) {
    document.documentElement.lang = lang;

    // Apply translations by data-i18n
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.getText(key, lang);
      if (text) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.value = text;
        } else {
          el.innerHTML = text;
        }
      }
    });

    // Apply placeholders by data-i18n-placeholder
    const placeholderEls = document.querySelectorAll('[data-i18n-placeholder]');
    placeholderEls.forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const text = this.getText(key, lang);
      if (text) {
        el.setAttribute('placeholder', text);
      }
    });

    // Update document title if configured
    const titleKey = this.pageScope + '.meta_title';
    const pageTitle = this.getText(titleKey, lang);
    if (pageTitle) {
      document.title = pageTitle;
    }

    // Update meta description
    const descKey = this.pageScope + '.meta_desc';
    const pageDesc = this.getText(descKey, lang);
    const metaDescTag = document.querySelector('meta[name="description"]');
    if (metaDescTag && pageDesc) {
      metaDescTag.setAttribute('content', pageDesc);
    }
  }

  getText(keyPath, lang) {
    const parts = keyPath.split('.');
    let obj = translations;

    // If key doesn't include section prefix, try pageScope then shared
    if (parts.length === 1) {
      if (translations[this.pageScope] && translations[this.pageScope][parts[0]]) {
        obj = translations[this.pageScope][parts[0]];
      } else if (translations.shared && translations.shared[parts[0]]) {
        obj = translations.shared[parts[0]];
      } else {
        return null;
      }
    } else {
      for (const p of parts) {
        if (!obj || !obj[p]) return null;
        obj = obj[p];
      }
    }

    if (typeof obj === 'object') {
      return obj[lang] || obj['id'] || '';
    }
    return obj;
  }

  renderLanguageSwitcher() {
    const switcherContainers = document.querySelectorAll('.lang-switcher-container');
    switcherContainers.forEach(container => {
      container.innerHTML = `
        <div class="inline-flex items-center p-0.5 rounded-lg bg-slate-800/80 border border-slate-700 text-xs font-semibold shadow-inner">
          <button type="button" onclick="window.i18n.setLanguage('id')" data-lang-btn="id" class="px-2.5 py-1 rounded transition-all flex items-center gap-1.5 ${this.currentLang === 'id' ? 'bg-sky-500 text-white shadow-sm' : 'text-slate-400 hover:text-slate-200'}">
            <span>🇮🇩</span> <span class="tracking-wide">ID</span>
          </button>
          <button type="button" onclick="window.i18n.setLanguage('en')" data-lang-btn="en" class="px-2.5 py-1 rounded transition-all flex items-center gap-1.5 ${this.currentLang === 'en' ? 'bg-sky-500 text-white shadow-sm' : 'text-slate-400 hover:text-slate-200'}">
            <span>🇬🇧</span> <span class="tracking-wide">EN</span>
          </button>
        </div>
      `;
    });
  }

  updateSwitcherUI() {
    const idBtns = document.querySelectorAll('[data-lang-btn="id"]');
    const enBtns = document.querySelectorAll('[data-lang-btn="en"]');

    idBtns.forEach(btn => {
      if (this.currentLang === 'id') {
        btn.className = "px-2.5 py-1 rounded transition-all flex items-center gap-1.5 bg-sky-500 text-white shadow-sm font-bold";
      } else {
        btn.className = "px-2.5 py-1 rounded transition-all flex items-center gap-1.5 text-slate-400 hover:text-slate-200";
      }
    });

    enBtns.forEach(btn => {
      if (this.currentLang === 'en') {
        btn.className = "px-2.5 py-1 rounded transition-all flex items-center gap-1.5 bg-sky-500 text-white shadow-sm font-bold";
      } else {
        btn.className = "px-2.5 py-1 rounded transition-all flex items-center gap-1.5 text-slate-400 hover:text-slate-200";
      }
    });
  }
}

// Global instance
window.i18n = new I18nManager();
